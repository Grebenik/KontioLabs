/* Generates site/study/topics/english-numbers.js — a full SRS topic deck of
   English cardinal (and a few ordinal) numbers — from an algorithmic
   English number-to-words function. Mirrors gen-finnish-numbers.js.
   Audience: learners whose known language is Russian; front = digits,
   back = the English word (with a Russian gloss on the vocab cards).
   Run: node gen-english-numbers.js */
'use strict';
const fs = require('fs');
const path = require('path');

const ONES = ['zero', 'one', 'two', 'three', 'four', 'five', 'six', 'seven', 'eight', 'nine'];
const TEENS = ['ten', 'eleven', 'twelve', 'thirteen', 'fourteen', 'fifteen', 'sixteen', 'seventeen', 'eighteen', 'nineteen'];
const TENS = ['twenty', 'thirty', 'forty', 'fifty', 'sixty', 'seventy', 'eighty', 'ninety'];
const ORDINALS_1_10 = ['first', 'second', 'third', 'fourth', 'fifth', 'sixth', 'seventh', 'eighth', 'ninth', 'tenth'];

function cardinal(n) {
  if (n < 0) throw new Error('negative not supported');
  if (n < 10) return ONES[n];
  if (n < 20) return TEENS[n - 10];
  if (n < 100) {
    const tens = Math.floor(n / 10), rem = n % 10;
    return TENS[tens - 2] + (rem ? '-' + ONES[rem] : '');
  }
  if (n < 1000) {
    const h = Math.floor(n / 100), rem = n % 100;
    return ONES[h] + ' hundred' + (rem ? ' and ' + cardinal(rem) : '');
  }
  if (n < 1000000) {
    const th = Math.floor(n / 1000), rem = n % 1000;
    return cardinal(th) + ' thousand' + (rem ? (rem < 100 ? ' and ' : ' ') + cardinal(rem) : '');
  }
  if (n < 1000000000) {
    const m = Math.floor(n / 1000000), rem = n % 1000000;
    return cardinal(m) + ' million' + (rem ? (rem < 100 ? ' and ' : ' ') + cardinal(rem) : '');
  }
  throw new Error('too large');
}

const cards = [];
let idx = 0;
function push(front, back, note) {
  idx += 1;
  const id = 'en-' + String(idx).padStart(3, '0');
  cards.push({ id, front, back: note ? back + '  (' + note + ')' : back });
}

/* 0-19: every number, individually. */
for (let n = 0; n <= 19; n++) push(String(n), cardinal(n));

/* 21-99: every multiple of 10, plus a representative "tens+ones" example
   for each decade so the hyphenation pattern is drilled without generating
   80 near-duplicate cards. */
for (let tens = 2; tens <= 9; tens++) {
  const base = tens * 10;
  push(String(base), cardinal(base));
  push(String(base + 1), cardinal(base + 1), 'pattern: tens + ones, hyphenated');
  push(String(base + 7), cardinal(base + 7));
}

/* Hundreds: every multiple of 100 to 900, plus a couple of compounds. */
for (let h = 1; h <= 9; h++) push(String(h * 100), cardinal(h * 100));
push('101', cardinal(101));
push('250', cardinal(250));
push('999', cardinal(999));

/* Thousands: round thousands + a couple of compounds. */
[1000, 2000, 5000, 10000, 20000, 100000].forEach((n) => push(String(n), cardinal(n)));
push('1234', cardinal(1234));
push('2026', cardinal(2026), 'this year');

/* Millions. */
[1000000, 2000000].forEach((n) => push(String(n), cardinal(n)));

/* Ordinals 1st-10th, since they're high-frequency and partly irregular. */
ORDINALS_1_10.forEach((word, i) => push((i + 1) + '.', word, 'ordinal'));

/* A few core number-related vocabulary cards. Front = English word,
   back = Russian gloss (this deck's audience is a Russian speaker). */
[
  ['number', 'число / номер (сама цифра)'],
  ['to count / to calculate', 'считать / вычислять'],
  ['half', 'половина'],
  ['a pair / couple', 'пара'],
  ['dozen', 'дюжина'],
  ['percent', 'процент'],
  ['zero', 'ноль (как понятие, не только цифра)'],
  ['plus', 'плюс'],
  ['minus', 'минус']
].forEach(([front, back]) => push(front, back, 'vocab'));

function esc(s) { return s.replace(/\\/g, '\\\\').replace(/"/g, '\\"'); }
const cardLines = cards.map((c) =>
  `    { id: "${c.id}", front: "${esc(c.front)}", back: "${esc(c.back)}" }`
).join(',\n');

const header = `/* Topic: English Numbers — cardinal numbers 0-2,000,000 (with representative
   compounds so every tens/hundreds/thousands pattern is drilled), ordinals
   1st-10th, and core counting vocabulary.
   Audience: Russian-speaking learners of English. Front = digits, back = the
   English word (vocab cards also carry a Russian gloss).
   GENERATED by scripts/gen-english-numbers.js — do not hand-edit; re-run the
   script instead. */
SRS.registerTopic({
  id: "english-numbers",
  group: "English",
  name: "English Numbers",
  description: "English cardinal numbers 0 to 2,000,000, ordinals 1st-10th, and core counting vocabulary — the numbers and text as written in English, useful for learners of any native language.",
  cards: [
${cardLines}
  ]
});
`;

const outPath = path.join(__dirname, '..', 'topics', 'english-numbers.js');
fs.writeFileSync(outPath, header, 'utf8');
console.log('Wrote', cards.length, 'cards to', outPath);
