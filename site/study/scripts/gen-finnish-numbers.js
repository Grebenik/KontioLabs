/* Generates site/study/topics/finnish-numbers.js — a full SRS topic deck of
   Finnish cardinal (and a few ordinal) numbers — from an algorithmic
   Finnish number-to-words function. Run: node gen-finnish-numbers.js */
'use strict';
const fs = require('fs');
const path = require('path');

const ONES = ['nolla', 'yksi', 'kaksi', 'kolme', 'neljä', 'viisi', 'kuusi', 'seitsemän', 'kahdeksan', 'yhdeksän'];
const ORDINALS_1_10 = ['nollas', 'ensimmäinen', 'toinen', 'kolmas', 'neljäs', 'viides', 'kuudes', 'seitsemäs', 'kahdeksas', 'yhdeksäs', 'kymmenes'];

function cardinal(n) {
  if (n < 0) throw new Error('negative not supported');
  if (n < 10) return ONES[n];
  if (n < 20) return n === 10 ? 'kymmenen' : ONES[n - 10] + 'toista';
  if (n < 100) {
    const tens = Math.floor(n / 10), rem = n % 10;
    return (tens > 1 ? ONES[tens] : '') + 'kymmentä' + (rem ? cardinal(rem) : '');
  }
  if (n < 1000) {
    const h = Math.floor(n / 100), rem = n % 100;
    return (h > 1 ? ONES[h] : '') + 'sata' + (rem ? cardinal(rem) : '');
  }
  if (n < 1000000) {
    const th = Math.floor(n / 1000), rem = n % 1000;
    return (th === 1 ? 'tuhat' : cardinal(th) + 'tuhatta') + (rem ? cardinal(rem) : '');
  }
  if (n < 1000000000) {
    const m = Math.floor(n / 1000000), rem = n % 1000000;
    return (m === 1 ? 'miljoona' : cardinal(m) + ' miljoonaa') + (rem ? ' ' + cardinal(rem) : '');
  }
  throw new Error('too large');
}

const cards = [];
let idx = 0;
function push(front, back, note) {
  idx += 1;
  const id = 'fn-' + String(idx).padStart(3, '0');
  cards.push({ id, front, back: note ? back + '  (' + note + ')' : back });
}

/* 0-19: every number, individually, incl. the irregular teens.
   (20 itself is emitted by the decades loop below — don't double it here.) */
for (let n = 0; n <= 19; n++) push(String(n), cardinal(n));

/* 21-99: every multiple of 10, plus a representative "tens+ones" example
   for each decade so the compounding pattern (kaksikymmentäyksi, …) is drilled
   without generating 80 near-duplicate cards. */
for (let tens = 2; tens <= 9; tens++) {
  const base = tens * 10;
  push(String(base), cardinal(base));
  push(String(base + 1), cardinal(base + 1), 'pattern: kymmenet + ones');
  push(String(base + 7), cardinal(base + 7));
}

/* Hundreds: every multiple of 100 to 900, plus a couple of compounds. */
for (let h = 1; h <= 9; h++) push(String(h * 100), cardinal(h * 100));
push('101', cardinal(101));
push('250', cardinal(250));
push('999', cardinal(999));

/* Thousands: round thousands + a couple of compounds. */
[1000, 2000, 5000, 10000, 20000, 100000].forEach((n) => push(String(n), cardinal(n)));
push('1234', cardinal(1234));
push('2026', cardinal(2026), 'this year');

/* Millions. */
[1000000, 2000000].forEach((n) => push(String(n), cardinal(n)));

/* Ordinals 0th-10th, since they're irregular/high-frequency. */
ORDINALS_1_10.forEach((word, n) => push(n + '.', word, 'ordinal'));

/* A few core number-related vocabulary cards. */
[
  ['numero', 'number / numeral (the digit/figure itself)'],
  ['luku', 'number (a numeric value, e.g. in math)'],
  ['laskea', 'to count / to calculate'],
  ['puoli', 'half'],
  ['pari', 'a pair / couple (also: "a few")'],
  ['tusina', 'dozen'],
  ['prosentti', 'percent'],
  ['nolla', 'zero (as a noun/concept, not just the digit)'],
  ['plus', 'plus'],
  ['miinus', 'minus']
].forEach(([front, back]) => push(front, back, 'vocab'));

function esc(s) { return s.replace(/\\/g, '\\\\').replace(/"/g, '\\"'); }
const cardLines = cards.map((c) =>
  `    { id: "${c.id}", front: "${esc(c.front)}", back: "${esc(c.back)}" }`
).join(',\n');

const header = `/* Topic: Finnish Numbers — cardinal numbers 0-2,000,000 (with representative
   compounds so every decade/hundred/thousand pattern is drilled), ordinals
   1st-10th, and core counting vocabulary.
   GENERATED by scripts/gen-finnish-numbers.js — do not hand-edit; re-run the
   script instead. Front = digits, back = the Finnish word. */
SRS.registerTopic({
  id: "finnish-numbers",
  name: "Finnish Numbers",
  description: "Finnish cardinal numbers 0 to 2,000,000, ordinals 1st-10th, and core counting vocabulary — generated programmatically for consistent number-formation patterns.",
  cards: [
${cardLines}
  ]
});
`;

const outPath = path.join(__dirname, '..', 'topics', 'finnish-numbers.js');
fs.writeFileSync(outPath, header, 'utf8');
console.log('Wrote', cards.length, 'cards to', outPath);
